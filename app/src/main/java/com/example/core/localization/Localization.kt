enum class AppLanguage(val code: String, val shortLabel: String, val nativeLabel: String) {
    ENGLISH("en", "EN", "English"),
    BANGLA("bn", "বাং", "বাংলা");

    companion object {
        fun fromCode(code: String?): AppLanguage =
            entries.firstOrNull { it.code == code } ?: BANGLA
    }
}

